const chapters = files.map(file => {
  const text = fs.readFileSync(path.join(source, file), 'utf8');
  const blocks = [...text.matchAll(/\\begin\{(definition|proposition|lemma|theorem|example|remark|proof)\}(?:\[([^\]]*)\])?([\s\S]*?)\\end\{\1\}/g)].map(m => ({
    kind: m[1], name: m[2], body: m[3].trim(),
    lines: [text.slice(0, m.index).split('\n').length, text.slice(0, m.index + m[0].length).split('\n').length],
  }));
  return {file, text, blocks};
});
const notes = [];
const coverage = [];
const augmentations = [];
const reused = [];
const corrections = [];
const r = String.raw;
function n(id, title, taxon, ch, blocks, deps, context, reason, body = null, after = '') {
  notes.push({id, title, taxon, ch, blocks, deps, context, reason, body, after});
  for (const b of blocks) coverage.push({file: files[ch - 1], sourceLines: chapters[ch - 1].blocks[b].lines, ids: [id], notes: reason});
}
function reuse(ch, blocks, ids, reason, proposedAddition = null) {
  for (const b of blocks) coverage.push({file: files[ch - 1], sourceLines: chapters[ch - 1].blocks[b].lines, ids, notes: reason});
  reused.push({ids, file: files[ch - 1], blocks, reason});
  if (proposedAddition) augmentations.push({id: ids[0], file: files[ch - 1], sourceLines: blocks.map(b => chapters[ch - 1].blocks[b].lines), reason, proposedAddition, status: 'parent-action-required; canonical-file-not-edited'});
}

