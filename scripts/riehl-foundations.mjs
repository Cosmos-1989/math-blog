function convert(text) {
  let s = expand(text).replace(/\\label\{[^}]+\}/g,'');
  s = s.replace(/\\ref\{([^}]+)\}/g, (_, label) => {
    if (!labels[label]) throw new Error(`Unknown label ${label}`);
    return `[普通协变 Yoneda 引理](${labels[label]})`;
  });
  s = s.replace(/\\begin\{align\*\}([\s\S]*?)\\end\{align\*\}/g, (_, t) => r`\[\begin{aligned}` + t + r`\end{aligned}\]`);
  const pieces = s.split(/(\\\[[\s\S]*?\\\])/g);
  return pieces.map(piece => {
    if (piece.startsWith(r`\[`)) {
      let math = piece.slice(2,-2).trim();
      if (math.includes(r`\begin{tikzcd}`)) {
        math = math.replace(r`\begin{tikzcd}`,r`\begin{tikzcd}[column sep=large,row sep=large]`);
        return '\\figure{\\tex{\\usepackage{amsmath,amssymb}\n\\usepackage{tikz-cd}}{\n' + math + '\n}}';
      }
      return '##{' + math + '}';
    }
    return piece.trim().split(/\n\s*\n/).filter(Boolean).map(p => '\\p{' + p.trim().replace(/\$([^$]+)\$/g, (_, m) => '#{' + m + '}') + '}').join('\n\n');
  }).filter(Boolean).join('\n\n');
}
